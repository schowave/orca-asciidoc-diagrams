// Payload "katex": KaTeX (fonts inlined as data: URIs by the build) plus an AsciiMath → LaTeX
// converter, for Asciidoctor's :stem: (asciimath and latexmath). Exposes globalThis.adocMath.
import katex from 'katex'
import AsciiMathParser from 'asciimath2tex'
import css from './katex-css' // generated by scripts/build.mjs (katex.min.css with data: fonts)

const style = document.createElement('style')
style.textContent = css
document.head.appendChild(style)

const asciimath = new AsciiMathParser()
;(globalThis as any).adocMath = {
  render(tex: string, display: boolean, kind: 'latexmath' | 'asciimath') {
    const latex = kind === 'asciimath' ? asciimath.parse(tex) : tex
    return katex.renderToString(latex, { displayMode: display, throwOnError: false, output: 'htmlAndMathml' })
  },
}
