// Pure helpers for scripts/agent-stats.mjs: measures of agent contributions from commit messages.
const AGENT_TRAILER = /^Assisted-by:\s*Claude Code\b/im

/** @param {{ subject: string, body: string }[]} commits  newest first; release commits are not counted */
export function computeStats(commits) {
  const own = commits.filter((c) => !/^Release v\d/.test(c.subject))
  const agent = own.filter((c) => AGENT_TRAILER.test(c.body))
  const reverts = own.filter((c) => /^Revert\b/i.test(c.subject))
  const agentReverts = agent.filter((c) => /^Revert\b/i.test(c.subject))
  const pct = (n, of) => (of === 0 ? 'n/a' : `${((100 * n) / of).toFixed(1)} %`)
  return {
    commits: own.length,
    agentCommits: agent.length,
    agentShare: pct(agent.length, own.length),
    reverts: reverts.length,
    revertRate: pct(reverts.length, own.length),
    agentReverts: agentReverts.length,
    agentRevertRate: pct(agentReverts.length, agent.length),
  }
}

export function renderStats(stats, asOf) {
  return `# Agent contribution measures

Generated by \`scripts/agent-stats.mjs\` from the git history (as of ${asOf}); the weekly release workflow refreshes it.
Agent commits carry the trailer \`Assisted-by: Claude Code\` (see \`AGENTS.md\`). Release commits are not counted.

| Measure | Value |
|---|---|
| Commits | ${stats.commits} |
| Agent commits | ${stats.agentCommits} |
| Agent share of commits | ${stats.agentShare} |
| Reverts | ${stats.reverts} |
| Revert rate, all commits | ${stats.revertRate} |
| Revert rate, agent commits | ${stats.agentRevertRate} (${stats.agentReverts} reverts) |
`
}
